const ALIAS = { '—': '-', '–': '-', '’': "'", '‘': "'", '“': '"', '”': '"', '…': '...', '×': 'x', '−': '-' };
const norm = (s) => [...s].map((ch) => ALIAS[ch] ?? ch).join('');
export const ROWS7 = 7;
export const has = (ch) => !!G[ch];
export function width(s) { let w = 0; for (const ch of norm(s)) w += (G[ch] || G[' '])[0].length + 1; return Math.max(0, w - 1); }
/* rasterise one line into grid (Float32Array cols*rows) at column x, row y with brightness lv.
   Columns outside 0..cols-1 are skipped, so a line can be scrolled through the window. */
export function blit(grid, cols, s, x, y, lv) {
  for (const ch of norm(s)) { const g = G[ch] || G[' '];
    for (let r = 0; r < 7; r++) for (let c = 0; c < g[r].length; c++) {
      const xx = x + c; if (xx < 0 || xx >= cols || g[r][c] !== '#') continue;
      grid[(y + r) * cols + xx] = lv; }
    x += g[0].length + 1; }
  return x;
}
